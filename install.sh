if [ "$DRY_RUN" -eq 1 ]; then
  ok "dry run — nothing was changed"
else
  up=0
  for _ in $(seq 1 10); do
    if curl -fs -o /dev/null "http://127.0.0.1:$OBS_PORT/healthz"; then up=1; break; fi
    sleep 1
  done
  [ "$up" -eq 1 ] && ok "observatory answering on :$OBS_PORT" \
    || warn "observatory not answering on :$OBS_PORT — journalctl -u meosar-observatory -n 20"
  if [ "$START_RX_NOW" = y ]; then
    sleep 5
    if systemctl is-active --quiet meosar-rx; then
      ok "receiver running — first records arrive within a minute or so"
    else
      warn "receiver not running — recent log:"
      journalctl -u meosar-rx -n 15 --no-pager 2>/dev/null | sed 's/^/      /' || true
    fi
  fi
fi

