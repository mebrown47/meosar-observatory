# install.sh — install, update or remove meosar-rx on this machine: the MEOSAR L-band
# receiver and the MEOSAR Observatory dashboard (:8896), as systemd services, with a rollup
# that folds the receiver's archive into the dashboard's database every minute and a daily
# archive tidy-up.
#
# Usage (from the source directory, as your normal user — it sudo's as needed):
#     ./install.sh                 first install (asks a few questions)
#     ./install.sh --update        git pull (if a git checkout), rebuild, test, reinstall, restart
#     ./install.sh --reconfigure   ask the questions again, then reinstall
#     ./install.sh --uninstall     remove services and program files
#
# Options:
#     --yes          don't ask; take the defaults (or the existing config)
#     --no-deps      skip installing packages (you've done it yourself)
#     --dry-run      print what would be done as root, change nothing
#     -h, --help     show this help
#
# Where things go:
#     /opt/meosar-rx/             program files (receiver, observatory)
#     /etc/meosar-rx.conf         your settings — edit this, not the units
#     /var/lib/meosar-rx/         archive/ (daily JSONL) and observatory.db
#
# Re-running is safe. Settings and archive survive updates and uninstall.
# Adapted from inmarsat-rx's installer.
#
set -euo pipefail

# ---- pretty output ----------------------------------------------------------
if [ -t 1 ]; then B=$'\e[1m'; G=$'\e[32m'; Y=$'\e[33m'; R=$'\e[31m'; Z=$'\e[0m'; else B=; G=; Y=; R=; Z=; fi
say()  { printf '%s\n' "$*"; }
info() { printf '\n%s==>%s %s\n' "$B" "$Z" "$*"; }
ok()   { printf '  %sok%s   %s\n' "$G" "$Z" "$*"; }
warn() { printf '  %swarn%s %s\n' "$Y" "$Z" "$*"; }
die()  { printf '  %serror%s %s\n' "$R" "$Z" "$*" >&2; exit 1; }

# ---- fixed locations --------------------------------------------------------
REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
BUILD_DIR="$REPO_ROOT/build-install"
PREFIX=/opt/meosar-rx
CONF=/etc/meosar-rx.conf
DATA_DIR=/var/lib/meosar-rx
ARCHIVE_DIR="$DATA_DIR/archive"
DB_PATH="$DATA_DIR/observatory.db"
UNIT_DIR=/etc/systemd/system
RX_UNIT="$UNIT_DIR/meosar-rx.service"
OBS_UNIT="$UNIT_DIR/meosar-observatory.service"
ROLLUP_UNIT="$UNIT_DIR/meosar-rollup.service"
ROLLUP_TIMER="$UNIT_DIR/meosar-rollup.timer"
TIDY_UNIT="$UNIT_DIR/meosar-tidy.service"
TIDY_TIMER="$UNIT_DIR/meosar-tidy.timer"
UNITS=(meosar-rx.service meosar-observatory.service meosar-rollup.timer meosar-tidy.timer)
ALL_UNIT_FILES=("$RX_UNIT" "$OBS_UNIT" "$ROLLUP_UNIT" "$ROLLUP_TIMER" "$TIDY_UNIT" "$TIDY_TIMER")
MARKER="# Generated by meosar-rx install.sh"
# Other programs on this station that may use the same Airspy.
SDR_NEIGHBOURS=(iridium-sniffer inmarsat-rx airspy-spyserver spyserver)

# ---- args -------------------------------------------------------------------
MODE=install; ASSUME_YES=0; DEPS=1; DRY_RUN=0; PULLED=0
ORIG_ARGS=("$@")
while [ $# -gt 0 ]; do
  case "$1" in
    --update)      MODE=update;;
    --reconfigure) MODE=reconfigure;;
    --uninstall)   MODE=uninstall;;
    --yes|-y)      ASSUME_YES=1;;
    --no-deps)     DEPS=0;;
    --dry-run)     DRY_RUN=1;;
    --pulled)      PULLED=1;;   # internal: --update re-running the new script
    -h|--help)     awk 'NR>4 && /^#/ {sub(/^# ?/, ""); print; next} NR>4 {exit}' "${BASH_SOURCE[0]}"; exit 0;;
    *) die "unknown option: $1 (try --help)";;
  esac
  shift
done

# ---- helpers ----------------------------------------------------------------
# Everything that changes the system outside the source directory goes through as_root,
# so --dry-run can show it without doing it.
as_root() {
  if [ "$DRY_RUN" -eq 1 ]; then printf '  %s[dry-run]%s %s\n' "$Y" "$Z" "$*"; return 0; fi
  sudo "$@"
}
root_write() {
  local dst="$1" mode="$2" tmp
  tmp="$(mktemp)"; cat > "$tmp"
  if [ "$DRY_RUN" -eq 1 ]; then
    printf '  %s[dry-run]%s write %s:\n' "$Y" "$Z" "$dst"; sed 's/^/      | /' "$tmp"
  else
    sudo install -m "$mode" "$tmp" "$dst"
  fi
  rm -f "$tmp"
}
ask() {
  local q="$1" def="$2" ans
  if [ "$ASSUME_YES" -eq 1 ] || [ ! -r /dev/tty ]; then printf '%s' "$def"; return; fi
  printf '  %s [%s]: ' "$q" "$def" > /dev/tty
  read -r ans < /dev/tty || ans=""
  printf '%s' "${ans:-$def}"
}
yes_no() { case "$(ask "$1 (y/n)" "$2")" in [Yy]*) return 0;; *) return 1;; esac; }
have() { command -v "$1" >/dev/null 2>&1; }
unit_exists() { systemctl list-unit-files "$1.service" 2>/dev/null | grep -q "^$1.service"; }
# PIDs (with command lines) listening on a TCP port that systemd didn't start as one of ours.
port_holders() {
  local port="$1"
  have ss || return 0
  ss -Hltnp "sport = :$port" 2>/dev/null | grep -o 'pid=[0-9]*' | cut -d= -f2 | sort -u | while read -r pid; do
    unit="$(ps -o unit= -p "$pid" 2>/dev/null | tr -d ' ')"
    case "$unit" in meosar-*.service) continue;; esac
    printf '%s %s\n' "$pid" "$(ps -o args= -p "$pid" 2>/dev/null)"
  done
}

# ---- preflight --------------------------------------------------------------
info "Preflight"
[ "$(uname -s)" = Linux ] || die "Linux only"
[ "$(id -u)" -ne 0 ] || die "run as your normal user, not root — it uses sudo when it needs to"
have systemctl || die "systemd is required"
have sudo || die "sudo is required"
if [ "$DRY_RUN" -eq 0 ]; then sudo -v || die "sudo failed"; fi
RUN_USER="$(id -un)"
ok "user: $RUN_USER   arch: $(uname -m)   $(. /etc/os-release 2>/dev/null; echo "${PRETTY_NAME:-unknown OS}")"

# ---- uninstall --------------------------------------------------------------
if [ "$MODE" = uninstall ]; then
  info "Removing services and program files"
  as_root systemctl disable --now "${UNITS[@]}" meosar-tidy.service meosar-rollup.service 2>/dev/null || true
  as_root rm -f "${ALL_UNIT_FILES[@]}" /usr/local/bin/meosar-rx
  as_root rm -rf "$PREFIX"
  as_root systemctl daemon-reload
  ok "removed. Kept: $CONF and $DATA_DIR (archive and database; delete by hand for a clean slate)"
  exit 0
fi

# ---- update: pull first, so everything below builds the new source ----------
if [ "$MODE" = update ] && [ "$PULLED" -eq 0 ]; then
  [ -f "$CONF" ] || die "no $CONF — run ./install.sh first"
  info "Updating the source"
  if have git && git -C "$REPO_ROOT" rev-parse --is-inside-work-tree >/dev/null 2>&1; then
    git -C "$REPO_ROOT" pull --ff-only \
      || die "git pull failed (local changes or a diverged branch?) — fix the checkout and re-run"
    ok "now at $(git -C "$REPO_ROOT" describe --always --dirty --tags)"
    exec "$REPO_ROOT/install.sh" "${ORIG_ARGS[@]}" --pulled
  fi
  warn "not a git checkout: rebuilding the source as it is (copy new source here first)"
fi

# ---- packages ---------------------------------------------------------------
if [ "$DEPS" -eq 1 ]; then
  info "Packages"
  if have apt-get; then
    PKGS=(build-essential cmake pkg-config git python3 curl usbutils iproute2 gzip
          libfftw3-dev libusb-1.0-0-dev libairspy-dev libhackrf-dev
          python3-sgp4)   # the observatory's satellite attribution
    as_root apt-get install -y -q --no-install-recommends "${PKGS[@]}" \
      || die "could not install the build tools — see apt's message above"
    ok "build tools, FFTW, Airspy and HackRF support, SGP4 installed"
  else
    warn "not a Debian/Ubuntu system — install by hand: cmake, a C compiler, pkg-config, FFTW3"
    warn "(single precision), libairspy, libhackrf, python3 (and its sgp4 module, for the observatory's"
    warn "satellite attribution), then re-run with --no-deps"
  fi
fi

# ---- build + test -----------------------------------------------------------
# Built here for this machine's CPU (-march=native): the FFTs are most of the work.
# Always from clean: source copied in with its own timestamps (rsync -a, a tarball) can look
# older than the last build, and make would keep the stale objects.
info "Building"
mkdir -p "$BUILD_DIR"
cmake -S "$REPO_ROOT" -B "$BUILD_DIR" -DCMAKE_BUILD_TYPE=Release > "$BUILD_DIR.log" 2>&1 \
  && cmake --build "$BUILD_DIR" --clean-first -j"$(nproc)" >> "$BUILD_DIR.log" 2>&1 \
  || { tail -20 "$BUILD_DIR.log"; die "build failed — full log: $BUILD_DIR.log"; }
BIN="$BUILD_DIR/meosar-rx"
ok "built $BIN"
grep -q 'libAIRSPY found' "$BUILD_DIR.log" || warn "built without libairspy: no Airspy input"
grep -q 'libHACKRF found' "$BUILD_DIR.log" || warn "built without libhackrf: no HackRF input"

info "Testing"
"$REPO_ROOT/tests/run_tests.sh" "$BUILD_DIR" > "$BUILD_DIR/tests.log" 2>&1 \
  || { tail -20 "$BUILD_DIR/tests.log"; die "tests failed — not installing. Log: $BUILD_DIR/tests.log"; }
ok "$(grep '^RESULT' "$BUILD_DIR/tests.log")"

# ---- device access ----------------------------------------------------------
# The service runs headless with SupplementaryGroups=plugdev, so the SDR's USB node must be
# group-writable by plugdev. The kernel's V4L2 airspy driver grabs an R2 on plug-in (it becomes
# a radio device and libairspy can't claim it), so it is blacklisted.
info "Device access"
SDR_RULE=/etc/udev/rules.d/52-meosar-rx.rules
if getent group plugdev >/dev/null 2>&1; then
  root_write "$SDR_RULE" 0644 <<'RULE'
# Written by meosar-rx install.sh: let the plugdev group (the meosar-rx service's) open an
# Airspy R2/Mini or a HackRF, logged in at the screen or not.
SUBSYSTEM=="usb", ATTR{idVendor}=="1d50", ATTR{idProduct}=="60a1", MODE="0660", GROUP="plugdev"
SUBSYSTEM=="usb", ATTR{idVendor}=="1d50", ATTR{idProduct}=="6089", MODE="0660", GROUP="plugdev"
SUBSYSTEM=="usb", ATTR{idVendor}=="1d50", ATTR{idProduct}=="cc15", MODE="0660", GROUP="plugdev"
RULE
  as_root udevadm control --reload-rules
  as_root udevadm trigger --subsystem-match=usb --attr-match=idVendor=1d50
  ok "udev rule: plugdev can open an Airspy or HackRF ($SDR_RULE)"
  if [[ " $(id -nG "$RUN_USER") " != *" plugdev "* ]]; then
    as_root usermod -aG plugdev "$RUN_USER"
    warn "added $RUN_USER to plugdev: log out and back in to use the SDR from your own shell"
  fi
else
  warn "no plugdev group on this system: the service may not be able to open the SDR"
fi
BLACKLIST=/etc/modprobe.d/blacklist-airspy-v4l2.conf
if [ ! -f "$BLACKLIST" ]; then
  printf '# Written by meosar-rx install.sh: libairspy, not the V4L2 driver, runs the R2.\nblacklist airspy\n' \
    | root_write "$BLACKLIST" 0644
  ok "kernel airspy (V4L2) driver blacklisted"
fi
if lsmod 2>/dev/null | grep -q '^airspy '; then as_root modprobe -r airspy || true; fi

# ---- current settings -------------------------------------------------------
# The parts of RX_ARGS the questions cover, so --reconfigure offers them as the defaults and
# changing one doesn't reset the rest; CUR_KEEP holds everything else, carried over as it is.
parse_current() {
  local -a w; read -r -a w <<<"$1"
  CUR_SRC=airspy; CUR_GAIN=""; CUR_BIAS=y; CUR_SGB=y; CUR_UDP=""; CUR_KEEP=""
  CUR_CENTER=1544.5e6; CUR_RATE=2.5e6; CUR_THREADS=4
  [ -n "$1" ] && CUR_BIAS=n
  local i=0 k v n=${#w[@]}
  while [ "$i" -lt "$n" ]; do
    k="${w[$i]}"; v=""; i=$((i+1))
    case "$k" in --*=*) v="${k#*=}"; k="${k%%=*}";; esac
    next() { if [ -z "$v" ] && [ "$i" -lt "$n" ]; then v="${w[$i]}"; i=$((i+1)); fi; }
    case "$k" in
      -i)            next; CUR_SRC="$v";;
      -g)            next; CUR_GAIN="$v";;
      -b)            CUR_BIAS=y;;
      -c)            next; CUR_CENTER="$v";;
      -s)            next; CUR_RATE="$v";;
      -u)            next; CUR_UDP+=" $v";;
      --no-sgb)      CUR_SGB=n;;
      --sgb-threads) next; CUR_THREADS="$v";;
      -q|--archive)  [ "$k" = --archive ] && next;;
      *)
        CUR_KEEP+=" ${w[$((i-1))]}"
        while [ "$i" -lt "$n" ] && [[ "${w[$i]}" != -* ]]; do CUR_KEEP+=" ${w[$i]}"; i=$((i+1)); done;;
    esac
  done
  CUR_UDP="$(echo $CUR_UDP)"; CUR_KEEP="$(echo $CUR_KEEP)"
}

# Which neighbours on this machine are set up to use an SDR (installed, enabled or running).
NEIGHBOURS=()
for other in "${SDR_NEIGHBOURS[@]}"; do unit_exists "$other" && NEIGHBOURS+=("$other"); done

# ---- config -----------------------------------------------------------------
if [ -f "$CONF" ] && [ "$MODE" != reconfigure ]; then
  info "Config"
  ok "keeping $CONF (./install.sh --reconfigure to redo it)"
  # shellcheck disable=SC1090
  . "$CONF"
else
  info "Config"
  OBS_PORT=8896; KEEP_DAYS=30; DEC406_HEX=""; STATION_POS=""; RX_ARGS=""; START_AT_BOOT=y; SHARE_WITH="-"
  STATION="$(hostname -s)"
  # shellcheck disable=SC1090
  [ -f "$CONF" ] && . "$CONF"
  parse_current "$RX_ARGS"
  [ -n "$RX_ARGS" ] && say "  Current settings are the defaults: press Enter to keep each one."
  say "  Sources: airspy[:SERIAL] (R2/Mini on USB), hackrf, rtl_tcp:HOST:PORT, spyserver:HOST:PORT"
  src="$(ask "Source" "$CUR_SRC")"
  case "$src" in
    airspy*)  gain="$(ask "Linearity gain 0-21 (18 suits a zenith patch with an LNA)" "${CUR_GAIN:-18}")";;
    hackrf*)  gain="$(ask "HackRF LNA,VGA in dB" "${CUR_GAIN:-32,20}")";;
    rtl_tcp*) gain="$(ask "Gain in dB, or auto" "${CUR_GAIN:-auto}")";;
    *)        gain="$(ask "Node gain index, or default" "${CUR_GAIN:-default}")";;
  esac
  RX_ARGS="-i $src -c $CUR_CENTER -s $CUR_RATE"
  case "$gain" in auto|default|"") ;; *) RX_ARGS+=" -g $gain";; esac
  case "$src" in airspy*|hackrf*|rtl_tcp*)
    yes_no "Power the antenna's LNA through the coax (bias-tee)" "$CUR_BIAS" && RX_ARGS+=" -b";;
  esac
  if yes_no "Search for second-generation (SGB) beacons too (about 1 more CPU core)" "$CUR_SGB"; then
    RX_ARGS+=" --sgb-threads $CUR_THREADS"
  else
    RX_ARGS+=" --no-sgb"
  fi
  feeds="$(ask "Feed records over UDP: HOST:PORT destinations, space-separated (none for none)" "${CUR_UDP:-none}")"
  if [ "$feeds" != none ]; then
    for f in $feeds; do RX_ARGS+=" -u $f"; done
  fi
  [ -n "$CUR_KEEP" ] && { RX_ARGS+=" $CUR_KEEP"; ok "kept as they were (edit $CONF to change them): $CUR_KEEP"; }
  RX_ARGS="$(echo "$RX_ARGS" | sed 's/^ *//; s/  */ /g; s/ *$//')"
  STATION="$(ask "Station name for the dashboard" "$STATION")"
  STATION_POS="$(ask "Station position, LAT,LON in degrees, to ~1 km: the globe and satellite attribution use it (none for none)" "${STATION_POS:-none}")"
  [ "$STATION_POS" = none ] && STATION_POS=""
  KEEP_DAYS="$(ask "Days of raw archive to keep (0 = keep everything; the database keeps every burst)" "$KEEP_DAYS")"
  # dec406's hex decoder gives the observatory each frame's fields and position.
  def_dec="${DEC406_HEX:-}"
  [ -z "$def_dec" ] && [ -x "$HOME/dec406/build/dec406_hex" ] && def_dec="$HOME/dec406/build/dec406_hex"
  DEC406_HEX="$(ask "dec406's hex decoder, for beacon fields and positions (none for none)" "${def_dec:-none}")"
  [ "$DEC406_HEX" = none ] && DEC406_HEX=""
  if [ -n "$DEC406_HEX" ] && [ ! -x "$DEC406_HEX" ]; then
    warn "$DEC406_HEX is not an executable: the observatory will show basic fields only"
  fi
  case "$KEEP_DAYS" in ''|*[!0-9]*) die "days must be a whole number";; esac
  # One SDR serves one program at a time. Another receiver here that uses the same SDR can be
  # made to take turns with this one: starting either stops the other (systemd Conflicts=).
  prev_share="$SHARE_WITH"; SHARE_WITH=""
  if [[ "$src" == airspy* || "$src" == hackrf* ]]; then
    for other in "${NEIGHBOURS[@]}"; do
      if [ "$prev_share" != - ]; then
        def=n; [[ " $prev_share " == *" $other "* ]] && def=y
      else   # first time: guess from the other unit's command line
        def=n; systemctl cat "$other" 2>/dev/null | grep -qi "${src%%:*}" && def=y
      fi
      if yes_no "$other is set up here — does it use this same SDR (then starting one stops the other)" "$def"; then
        SHARE_WITH+=" $other"
        systemctl is-enabled --quiet "$other" 2>/dev/null && START_AT_BOOT=n
      fi
    done
  fi
  SHARE_WITH="$(echo $SHARE_WITH)"
  [ "$START_AT_BOOT" = n ] && say "  $SHARE_WITH starts at boot, so by default meosar-rx doesn't: they'd fight over the SDR."
  START_AT_BOOT="$(yes_no "Start the receiver at boot" "$START_AT_BOOT" && echo y || echo n)"
  root_write "$CONF" 0644 <<EOF
# meosar-rx settings — written by install.sh, yours to edit.
# After changing RX_ARGS:     sudo systemctl restart meosar-rx
# Anything else changed?      re-run ./install.sh so the services follow.
# All receiver options:       meosar-rx --help
#
# Archive in $ARCHIVE_DIR (one file per UTC day), database $DB_PATH.

# Who the services run as.
RUN_USER="$RUN_USER"

# Receiver flags (source, frequency, rate, gain, feeds). -q, --archive and --stats are added for you.
RX_ARGS="$RX_ARGS"

# Station name on the dashboard, and its position on the globe (LAT,LON; "" = not shown).
STATION="$STATION"
STATION_POS="$STATION_POS"

# Observatory dashboard port.
OBS_PORT="$OBS_PORT"

# dec406's hex decoder, for each frame's fields and position ("" = basic fields only).
DEC406_HEX="$DEC406_HEX"

# Days of raw archive to keep; files older than a day are compressed. 0 keeps everything.
# The observatory database keeps every burst regardless.
KEEP_DAYS="$KEEP_DAYS"

# y: start the receiver at boot.
START_AT_BOOT="$START_AT_BOOT"

# Services that use the same SDR: starting meosar-rx stops them, and starting one of them
# stops meosar-rx (re-run ./install.sh after changing this).
SHARE_WITH="$SHARE_WITH"
EOF
  ok "wrote $CONF"
fi
: "${OBS_PORT:=8896}" "${KEEP_DAYS:=30}" "${DEC406_HEX:=}" "${RUN_USER:=$(id -un)}"
: "${STATION_POS:=}" "${STATION:=$(hostname -s)}" "${START_AT_BOOT:=y}" "${SHARE_WITH:=}"
[ "$SHARE_WITH" = - ] && SHARE_WITH=""

# ---- install files ----------------------------------------------------------
info "Installing program files to $PREFIX"
STAGE="$(mktemp -d)"; trap 'rm -rf "$STAGE"' EXIT
mkdir -p "$STAGE/bin" "$STAGE/observatory"
cp "$BIN" "$STAGE/bin/"
cp "$REPO_ROOT"/observatory/{rollup.py,satattr.py,server.py,page.html,globe.html} "$STAGE/observatory/"
cp -r "$REPO_ROOT"/observatory/static "$STAGE/observatory/"   # the globe's script and vendored assets
cat > "$STAGE/bin/meosar-tidy" <<'EOF'
#!/bin/sh
# Compress archive files older than a day; delete those older than KEEP_DAYS (0 = never).
set -eu
dir="$1"; keep="$2"
find "$dir" -maxdepth 1 -name 'meosar-*.jsonl' -mtime +0 -exec gzip -9 {} \;
[ "$keep" -gt 0 ] && find "$dir" -maxdepth 1 -name 'meosar-*.jsonl.gz' -mtime +"$keep" -delete
exit 0
EOF
chmod +x "$STAGE/bin/meosar-tidy"
if git -C "$REPO_ROOT" rev-parse --is-inside-work-tree >/dev/null 2>&1; then
  git -C "$REPO_ROOT" describe --always --dirty --tags > "$STAGE/VERSION"
else
  echo "unknown (not a git checkout), built $(date -u +%Y-%m-%dT%H:%MZ)" > "$STAGE/VERSION"
fi
# Swap the whole tree in by rename, so the services never see half a copy.
as_root rm -rf "$PREFIX.new" "$PREFIX.old"
as_root cp -r "$STAGE" "$PREFIX.new"
as_root chmod -R a+rX "$PREFIX.new"
if [ "$DRY_RUN" -eq 1 ] || [ -d "$PREFIX" ]; then as_root mv "$PREFIX" "$PREFIX.old"; fi
as_root mv "$PREFIX.new" "$PREFIX"
as_root rm -rf "$PREFIX.old"
as_root ln -sf "$PREFIX/bin/meosar-rx" /usr/local/bin/meosar-rx
ok "version $(cat "$STAGE/VERSION")"
as_root mkdir -p "$ARCHIVE_DIR"
as_root chown -R "$RUN_USER:" "$DATA_DIR"
ok "data in $DATA_DIR"

# ---- things already holding the SDR or the ports ----------------------------
# Hand-started copies (setsid/nohup) of the receiver or dashboards would hold the SDR or the
# ports, and the services would fail to start.
info "Checking for hand-started copies"
STOP_PIDS=(); FOUND=0
# (8897 was the old local-only view.)
for port in "$OBS_PORT" 8897; do
  while read -r pid args; do
    [ -n "${pid:-}" ] || continue
    FOUND=1
    if [[ "$args" == *server.py* ]] && yes_no "Port $port is held by PID $pid ($args) — stop it" y; then
      STOP_PIDS+=("$pid")
    else
      warn "port $port is held by PID $pid ($args)"
    fi
  done < <(port_holders "$port")
done
RX_HAND="$(pgrep -u "$RUN_USER" -a -x meosar-rx 2>/dev/null | grep -v "$PREFIX/bin" || true)"
if [ -n "$RX_HAND" ]; then
  say "  A meosar-rx you started by hand is running:"
  say "      $RX_HAND"
  if yes_no "Stop it so the service can have the SDR" n; then
    STOP_PIDS+=($(awk '{print $1}' <<<"$RX_HAND"))
  else
    warn "leaving it running: the receiver service is installed but not started this time"
    START_RX_NOW=n
  fi
fi
for pid in "${STOP_PIDS[@]}"; do
  if [ "$DRY_RUN" -eq 1 ]; then printf '  %s[dry-run]%s kill %s\n' "$Y" "$Z" "$pid"
  else kill "$pid" 2>/dev/null && ok "stopped PID $pid"; fi
done
[ "${#STOP_PIDS[@]}" -gt 0 ] && [ "$DRY_RUN" -eq 0 ] && sleep 2
[ "$FOUND" -eq 0 ] && [ -z "$RX_HAND" ] && ok "none"

# ---- services ---------------------------------------------------------------
info "Services"
for u in "${ALL_UNIT_FILES[@]}"; do
  if [ -f "$u" ] && ! head -1 "$u" | grep -qF "$MARKER"; then
    BAKU="$DATA_DIR/$(basename "$u").$(date +%Y%m%d-%H%M%S)"
    as_root cp "$u" "$BAKU"
    warn "replacing a hand-written $u (saved a copy as $BAKU)"
  fi
done
GROUPS_LINE=""
getent group plugdev >/dev/null 2>&1 && GROUPS_LINE="SupplementaryGroups=plugdev"
CONFLICTS_LINE=""
if [ -n "$SHARE_WITH" ]; then
  CONFLICTS_LINE="Conflicts=$(for o in $SHARE_WITH; do printf '%s.service ' "$o"; done)"
fi
PY="$(command -v python3)"
root_write "$RX_UNIT" 0644 <<EOF
$MARKER — don't edit; change $CONF instead.
[Unit]
Description=meosar-rx MEOSAR L-band receiver (archive in $ARCHIVE_DIR)
After=network-online.target
Wants=network-online.target
$CONFLICTS_LINE

[Service]
Type=simple
User=$RUN_USER
$GROUPS_LINE
EnvironmentFile=$CONF
WorkingDirectory=$DATA_DIR
Nice=5
ExecStart=$PREFIX/bin/meosar-rx \$RX_ARGS -q --archive $ARCHIVE_DIR --stats 600
Restart=always
RestartSec=10

[Install]
WantedBy=multi-user.target
EOF
DEC_ARG="--dec406 ''"
