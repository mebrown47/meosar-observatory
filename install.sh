      as_root apt-get install -y -q --no-install-recommends rtl-sdr || die "could not install rtl-sdr (rtl_tcp)"
    else
      die "rtl_tcp not found: install the rtl-sdr tools and re-run"
    fi
  fi
  RTL_TCP_BIN="$(command -v rtl_tcp || echo /usr/bin/rtl_tcp)"
  ok "rtl_tcp: $RTL_TCP_BIN, serving the dongle on 127.0.0.1:$RTL_PORT ($RTL_TCP_ARGS)"
  # The DVB-T driver takes the dongle when it's plugged in, and then rtl_tcp can't open it:
  # blacklisted for good (the rtl-sdr packages usually do this; a build from source doesn't).
  if ! grep -rqs '^[[:space:]]*blacklist[[:space:]]\+dvb_usb_rtl28xxu' /etc/modprobe.d/; then
    { echo "# Written by meosar-rx install.sh: keep the DVB-T driver off RTL-SDR dongles"
      printf 'blacklist %s\n' "${DVB_MODS[@]}"; } | root_write /etc/modprobe.d/blacklist-rtl-sdr-dvb.conf 0644
    ok "DVB-T driver blacklisted (/etc/modprobe.d/blacklist-rtl-sdr-dvb.conf)"
  fi
  if lsmod 2>/dev/null | grep -q '^dvb_usb_rtl28xxu '; then
    for m in "${DVB_MODS[@]}"; do
      lsmod | grep -q "^$m " && { as_root modprobe -r "$m" || true; }
    done
    if [ "$DRY_RUN" -eq 0 ] && lsmod | grep -q '^dvb_usb_rtl28xxu '; then
      warn "the DVB-T driver still has the dongle: unplug it and plug it back in (the blacklist keeps the"
      warn "driver off now), then: sudo systemctl restart meosar-rx"
    else
      ok "DVB-T driver unloaded"
    fi
  fi
fi

