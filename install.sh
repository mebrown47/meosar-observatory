# Start (or restart) the receiver now — unless that would take the SDR from something else.
START_RX_NOW="${START_RX_NOW:-y}"
BUSY=()
for other in $SHARE_WITH; do systemctl is-active --quiet "$other" 2>/dev/null && BUSY+=("$other"); done
if [ "$START_RX_NOW" = y ] && [ "${#BUSY[@]}" -gt 0 ]; then
  yes_no "${BUSY[*]} is running and has the SDR — stop it and start meosar-rx now" n || START_RX_NOW=n
fi
if [ "$START_RX_NOW" = y ]; then
  as_root systemctl restart meosar-rx.service
  ok "meosar-rx (re)started"
else
  systemctl is-active --quiet meosar-rx 2>/dev/null && as_root systemctl stop meosar-rx.service
  ok "meosar-rx not started now"
fi

# ---- health -----------------------------------------------------------------
info "Checking"
